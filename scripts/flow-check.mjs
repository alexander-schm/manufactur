import { chromium } from 'playwright';
const base = process.argv[2];
const b = await chromium.launch({ channel: 'chrome' });
const ctx = await b.newContext({ viewport: { width: 1280, height: 860 }, deviceScaleFactor: 1 });
const page = await ctx.newPage();
const errs = []; page.on('pageerror', (e) => errs.push(e.message)); page.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await page.goto(base, { waitUntil: 'networkidle' });
await page.screenshot({ path: 'docs/screens/auth-desktop.png' });
const name = 'Tester' + Date.now() % 100000;
await page.fill('input[placeholder="z. B. Tonhausen"]', 'Tonhausen');
await page.locator('label:has-text("Dein Name") input').fill(name);
await page.locator('input[type=password]').fill('geheim123');
await page.click('form button[type=submit]');
await page.waitForSelector('.invite-code');
const code = await page.textContent('.invite-code');
await page.screenshot({ path: 'docs/screens/invite-desktop.png' });
await page.click('text=Los geht’s!');
await page.waitForSelector('.scene');
await page.waitForTimeout(1500);
await page.screenshot({ path: 'docs/screens/game-desktop.png' });
await page.reload({ waitUntil: 'networkidle' });
await page.waitForSelector('.scene', { timeout: 5000 });
console.log('session persists after reload: yes');
await page.click('[aria-label="Menü"]');
await page.click('text=Abmelden');
await page.waitForSelector('.auth-form');
await page.click('role=tab[name="Anmelden"]');
await page.locator('label:has-text("Dein Name") input').fill(name);
await page.locator('input[type=password]').fill('geheim123');
await page.click('form button[type=submit]');
await page.waitForSelector('.scene', { timeout: 5000 });
console.log('logout + login: yes; invite code', code);
console.log('errors:', errs.length ? errs.join(' | ') : 'none');
await b.close();
